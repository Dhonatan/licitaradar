require "test_helper"

class TenderTest < ActiveSupport::TestCase
  def create_tender(**attributes)
    @sequence = @sequence.to_i + 1
    number = @sequence.to_s.rjust(6, "0")
    Tender.create!({
      pncp_control_number: "00000000000191-1-#{number}/2026",
      modality_id: 6,
      status_id: Tender::PUBLISHED_STATUS_ID,
      state: "PE",
      object_description: "Serviços de comunicação institucional",
      estimated_value: 10_000,
      proposals_close_at: 5.days.from_now
    }.merge(attributes))
  end

  test "requires a unique PNCP control number" do
    tender = create_tender
    duplicate = Tender.new(pncp_control_number: tender.pncp_control_number)

    assert_not duplicate.valid?
    assert_includes duplicate.errors[:pncp_control_number], "já está em uso"
    assert_not Tender.new.valid?
  end

  test "validates modality, state and values" do
    tender = Tender.new(pncp_control_number: "x", modality_id: 99, state: "Pernambuco", estimated_value: -1)

    assert_not tender.valid?
    assert tender.errors.key?(:modality_id)
    assert tender.errors.key?(:state)
    assert tender.errors.key?(:estimated_value)
  end

  test "open_for_proposals keeps published tenders whose deadline is in the future" do
    open = create_tender
    closed = create_tender(proposals_close_at: 1.hour.ago)
    suspended = create_tender(status_id: 3)
    no_deadline = create_tender(proposals_close_at: nil)

    result = Tender.open_for_proposals

    assert_includes result, open
    assert_not_includes result, closed
    assert_not_includes result, suspended
    assert_not_includes result, no_deadline
    assert open.open_for_proposals?
    assert_not closed.open_for_proposals?
  end

  test "closing_within returns open tenders closing in the next N days" do
    soon = create_tender(proposals_close_at: 2.days.from_now)
    later = create_tender(proposals_close_at: 20.days.from_now)
    closed = create_tender(proposals_close_at: 1.day.ago)

    result = Tender.closing_within(3)

    assert_equal [ soon ], result.to_a
    assert_not_includes result, later
    assert_not_includes result, closed
  end

  test "in_state filters by one or more states, case-insensitively, and ignores blanks" do
    pe = create_tender(state: "PE")
    ba = create_tender(state: "BA")
    al = create_tender(state: "AL")

    assert_equal [ pe ], Tender.in_state("pe").to_a
    assert_equal [ pe, ba ], Tender.in_state([ "PE", "ba", "" ]).order(:id).to_a
    assert_equal 3, Tender.in_state([ "" ]).count
    assert_includes Tender.in_state(nil), al
  end

  test "of_modality filters by modality ids given as strings or integers" do
    pregao = create_tender(modality_id: 6)
    dispensa = create_tender(modality_id: 8)

    assert_equal [ dispensa ], Tender.of_modality("8").to_a
    assert_equal 2, Tender.of_modality([ 6, "8" ]).count
    assert_includes Tender.of_modality([]), pregao
  end

  test "value_between accepts open-ended ranges" do
    small = create_tender(estimated_value: 5_000)
    medium = create_tender(estimated_value: 50_000)
    large = create_tender(estimated_value: 500_000)

    assert_equal [ medium ], Tender.value_between(10_000, 100_000).to_a
    assert_equal [ medium, large ], Tender.value_between("10000", nil).order(:estimated_value).to_a
    assert_equal [ small, medium ], Tender.value_between("", 50_000).order(:estimated_value).to_a
    assert_equal 3, Tender.value_between(nil, "").count
  end

  test "zero or missing estimate is a confidential value" do
    assert Tender.new(estimated_value: 0).confidential_value?
    assert Tender.new(estimated_value: nil).confidential_value?
    assert_not Tender.new(estimated_value: 1).confidential_value?
  end

  test "searchable column is generated by the database" do
    create_tender(object_description: "Contratação de agência de publicidade")

    assert Tender.where("searchable @@ plainto_tsquery('portuguese', ?)", "publicidade").exists?
    assert_not Tender.where("searchable @@ plainto_tsquery('portuguese', ?)", "asfalto").exists?
  end

  test "searchable column ignores accents on both sides" do
    agencia = create_tender(object_description: "Contratação de AGÊNCIA de comunicação")
    create_tender(object_description: "Aquisição de material de limpeza")

    [ "agencia", "agência", "Comunicacao" ].each do |term|
      result = Tender.where("searchable @@ websearch_to_tsquery('portuguese', ?)", Tender.fold_accents(term))

      assert_equal [ agencia ], result.to_a, "expected #{term.inspect} to match"
    end
  end

  test "fold_accents strips Portuguese diacritics and keeps everything else" do
    assert_equal "Licitacao publica sao joao", Tender.fold_accents("Licitação pública são joão")
    assert_equal "ACAO", Tender.fold_accents("AÇÃO")
    assert_equal "", Tender.fold_accents(nil)
    assert_equal Tender::ACCENTED.length, Tender::UNACCENTED.length
  end

  test "accent table matches the one used by the searchable column" do
    require Rails.root.join("db/migrate/20261119130000_fold_accents_in_tenders_searchable")

    assert_equal FoldAccentsInTendersSearchable::ACCENTED, Tender::ACCENTED
    assert_equal FoldAccentsInTendersSearchable::UNACCENTED, Tender::UNACCENTED
  end
end
